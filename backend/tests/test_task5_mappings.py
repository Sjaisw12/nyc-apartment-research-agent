def test_2017_versus_2021_comparison_is_complete(mapping, pdf, measured):
    cmp = mapping["dob_definition_comparison"]
    table = measured["disposition_code_table"]
    assert set(cmp["in_2017_table_not_in_2021_pdf"]) == set(table) - set(pdf["codes"])
    assert set(cmp["in_2021_pdf_not_in_2017_table"]) == set(pdf["codes"]) - set(table)
    both = set(table) & set(pdf["codes"])
    differs = {d["code"] for d in cmp["in_both_wording_differs"]}
    assert len(differs) + len(cmp["in_both_ecb_renamed_oath"]) + cmp[
        "in_both_same_after_normalization"
    ] == len(both)
