"""Task 5: the proposed DOB disposition mapping agrees with its sources and rules.

Reads the committed files only (no network, no database):
- docs/task5/dob_disposition_codes_2021.json: codes extracted from DOB's PDF, Rev. 09/21;
- docs/task5/step1_measurements.json: the recorded step-1 counts (04:39Z);
- docs/task5/proposed_mappings.json: generated by scripts/task5_mappings.py.

Checks that every code in use is classified once, that only officially defined codes
get an outcome, that the wording of each code matches its outcome (prepared, served,
issued, corrective action), that the order-event table holds U4 and U5, and that the
counts come from the recorded measurements rather than a new snapshot.
"""

import importlib.util
import json
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs" / "task5"
SCRIPT = ROOT / "backend" / "scripts" / "task5_mappings.py"
PDF_SHA256 = "7ee93140b24d56fec2bacddc3c5f6037ab3b377c7d112440c2a322f3efc636ba"

ALLOWED_OUTCOMES = {
    "violation_served",
    "violation_issued",
    "violation_prepared_not_served",
    "corrective_action_requested",
    "corrective_action_corrected",
    "corrective_action_not_corrected",
    "order_event",
    "no_violation",
    "inspection_completed",
    "inspection_passed",
    "inspection_failed",
    "inspection_findings_under_review",
    "unsubstantiated",
    "no_access",
    "referred",
    "assigned_or_pending",
    "other_recorded",
    "unknown_code",
}
ORDER_WORDS = re.compile(r"STOP WORK|STOP ALL WORK|SWO|VACATE|PADLOCK", re.IGNORECASE)


def _load(name: str) -> dict:
    return json.loads((DOCS / name).read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def mapping() -> dict:
    return _load("proposed_mappings.json")


@pytest.fixture(scope="module")
def rows(mapping) -> dict[str, dict]:
    return {r["code"]: r for r in mapping["dob_disposition"]}


@pytest.fixture(scope="module")
def pdf() -> dict:
    return _load("dob_disposition_codes_2021.json")


@pytest.fixture(scope="module")
def measured() -> dict:
    return _load("step1_measurements.json")["results"]


@pytest.fixture(scope="module")
def script():
    spec = importlib.util.spec_from_file_location("task5_mappings", SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_source_is_the_user_supplied_pdf_with_recorded_hash(mapping, pdf):
    assert pdf["sha256"] == PDF_SHA256
    assert pdf["source_url"].endswith("/buildings/pdf/bis_complaint_disposition_codes.pdf")
    assert "supplied through the project" in pdf["obtained"]
    assert pdf["code_count"] == len(pdf["codes"]) == 184
    assert mapping["sources"]["dob_pdf_2021"]["sha256"] == PDF_SHA256
    assert mapping["status"].startswith("PROPOSED")


def test_counts_come_from_the_recorded_measurements(mapping):
    assert "step1_measurements.json" in mapping["sources"]["counts"]
    assert "no new snapshot" in mapping["sources"]["counts"]


def test_every_code_in_use_and_every_defined_code_appears_once(mapping, rows, pdf, measured):
    codes = [r["code"] for r in mapping["dob_disposition"]]
    assert len(codes) == len(set(codes))
    in_use = {c for c in measured["dob_disposition_codes_in_use"] if c != "None"}
    assert in_use <= set(rows)
    assert set(pdf["codes"]) <= set(rows)
    assert set(measured["disposition_code_table"]) <= set(rows)
    for c, n in measured["dob_disposition_codes_in_use"].items():
        if c != "None":
            assert rows[c]["rows_in_use"] == n


def test_outcomes_are_from_the_allowed_set(rows):
    assert {r["outcome"] for r in rows.values()} <= ALLOWED_OUTCOMES


def test_only_officially_defined_codes_get_an_outcome(rows, pdf, measured):
    table = measured["disposition_code_table"]
    for c, r in rows.items():
        if r["outcome"] == "unknown_code":
            assert r["definition"] is None and r["definition_source"] is None
            assert c not in pdf["codes"] and c not in table
            assert r["order_event"] is None
        else:
            assert r["definition"], c
            assert r["definition_source"] in ("dob_pdf_2021", "ref_6v9u_ndjg_2017")


def test_definitions_are_verbatim_and_2021_preferred(rows, pdf, measured):
    table = measured["disposition_code_table"]
    for c, r in rows.items():
        assert r["definition_2021_pdf"] == pdf["codes"].get(c)
        assert r["definition_2017_table"] == table.get(c)
        if c in pdf["codes"]:
            assert r["definition"] == pdf["codes"][c]
            assert r["definition_source"] == "dob_pdf_2021"


def test_outcomes_match_the_generator_rules(rows, pdf, measured, script):
    defined = set(pdf["codes"]) | set(measured["disposition_code_table"])
    for c, r in rows.items():
        assert r["outcome"] == script.outcome(c, defined), c
        assert r["order_event"] == script.ORDER_EVENTS.get(c), c
    listed = [c for codes in script.OUTCOMES.values() for c in codes]
    assert len(listed) == len(set(listed)), "a code is listed under two outcomes"


def test_resolved_and_unknown_counts(mapping, measured):
    s = mapping["dob_summary"]
