def test_prepared_served_and_issued_follow_the_official_wording(rows):
    for r in rows.values():
        text = (r["definition"] or "").upper()
        if r["outcome"] == "violation_prepared_not_served":
            assert "PREPARED" in text and "ATTEMPT TO SERVE" in text
        elif r["outcome"] == "violation_served":
            assert "SERVED" in text
        elif r["outcome"] == "violation_issued":
            assert "SERVED" not in text
            assert "ISSUED" in text or "WRITTEN" in text
    assert rows["B1"]["outcome"] == "violation_prepared_not_served"
    assert rows["B2"]["outcome"] == "violation_prepared_not_served"


def test_corrective_action_stages_are_distinct(rows):
    assert rows["AA"]["outcome"] == "corrective_action_requested"
    assert rows["AB"]["outcome"] == "corrective_action_corrected"
    assert rows["AC"]["outcome"] == "corrective_action_not_corrected"
    for c in ("AA", "AB", "AC"):
        assert "REQUEST FOR CORRECTIVE ACTION" in rows[c]["definition"].upper()


def test_inspection_completed_is_not_a_violation_or_a_pass(rows):
    assert rows["I3"]["outcome"] == "inspection_completed"
    assert rows["V1"]["outcome"] == "inspection_passed"
    assert rows["V2"]["outcome"] == "inspection_failed"


def test_order_event_table_includes_u4_and_u5(rows):
    assert rows["U4"]["outcome"] == "order_event"
    assert rows["U4"]["order_event"] == "stop_work_full_issued"
    assert rows["U4"]["order_action"] == "issued"
    assert rows["U5"]["outcome"] == "order_event"
    assert rows["U5"]["order_event"] == "stop_work_partial_issued"
    assert rows["U5"]["order_action"] == "issued"


def test_order_events_match_the_official_text(rows):
    for c, r in rows.items():
        text = r["definition"] or ""
        if r["order_event"]:
            assert ORDER_WORDS.search(text), c
        if r["outcome"] == "order_event":
            assert r["order_event"], c
        elif r["outcome"] == "assigned_or_pending" and ORDER_WORDS.search(text):
            # A7 and E2 name the Padlock Unit: an assignment, not an order.
            assert "PADLOCK UNIT" in text.upper(), c
        elif ORDER_WORDS.search(text) and r["outcome"] != "unknown_code":
            # A violation for disobeying an order, or a violation issued with one.
            assert r["order_event"], c
            assert r["outcome"] in ("violation_served", "violation_issued"), c


def test_order_action_keeps_served_apart_from_issued(rows):
    for c, r in rows.items():
        text = (r["definition"] or "").upper()
        action = r["order_action"]
        if not r["order_event"]:
            assert action is None
        elif r["order_event"].endswith("_noncompliance"):
            assert action == "noncompliance_violation"
        elif "RESCINDED" in text:
            assert action == "rescinded" and "rescinded" in r["order_event"], c
        elif action == "served":
            assert "SERVED" in text
        elif action == "issued":
            assert "ISSUED" in text and "SERVED" not in text
    assert rows["A7"]["order_event"] is None and rows["E2"]["order_event"] is None
    assert rows["A3"]["order_action"] == "served"
    assert rows["L1"]["order_action"] == "not_stated"


def test_no_label_claims_an_order_is_in_effect(rows, mapping):
    for r in rows.values():
        for label in (r["outcome"], r["order_event"] or "", r["order_action"] or ""):
            assert not re.search(r"active|in_effect|current|ongoing", label), label
    assert "No order event means an order is currently in effect" in (
        DOCS / "proposed_mappings.md"
    ).read_text(encoding="utf-8")


